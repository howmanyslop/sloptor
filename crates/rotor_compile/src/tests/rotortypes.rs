//! `rotortypes_test.go`

use rotor_tsrs::project::{ENV_DECL_BODY, MACRO_DECL_BODY};

use super::Temp;
use crate::rotortypes::{ROTOR_TYPES_FILE_NAME, rotor_types_file_text, write_rotor_types};

#[test]
fn write_rotor_types_cases() {
	let temp = Temp::new();
	let path = temp.join(ROTOR_TYPES_FILE_NAME);

	let wrote = write_rotor_types(&temp.dir()).expect("the first write");
	assert!(wrote, "missing file: wrote = false, want true");
	let data = std::fs::read_to_string(&path).expect("rotor.d.ts reads");
	assert_eq!(
		data,
		rotor_types_file_text(),
		"written content differs from RotorTypesFileText"
	);

	for want in [
		"declare const $env",
		"declare function $nameof(",
		"declare function $keys<",
		"declare function $file(",
	] {
		assert!(data.contains(want), "rotor.d.ts missing declaration {want:?}");
	}
	for body in [ENV_DECL_BODY, MACRO_DECL_BODY] {
		assert!(
			data.contains(body),
			"rotor.d.ts no longer contains a synthetic declaration body verbatim"
		);
	}
	assert!(
		data.contains("Generated by rotor; do not edit"),
		"rotor.d.ts is missing the generated-file header"
	);

	let wrote = write_rotor_types(&temp.dir());
	assert!(
		matches!(wrote, Ok(false)),
		"up-to-date file: wrote = {wrote:?}; want Ok(false)"
	);

	std::fs::write(&path, "// stale\n").expect("the stale file writes");
	let wrote = write_rotor_types(&temp.dir());
	assert!(
		matches!(wrote, Ok(true)),
		"stale file: wrote = {wrote:?}; want Ok(true)"
	);
}
